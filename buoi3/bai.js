let x = 3;
let y = 1;
let pt = '+';
switch(pt) {
     case '+':
        console.log("x + y = " + (x+y));
        break;
    case '-':
        console.log("x - y = " + (x-y));
        break;
    case '*':
        console.log("x * y = " + (x*y));
        break;
    case '/':
        console.log("x / y = " + (x/y));
        break;
    default:
        console.log("Phép tính không hợp lệ.");
}

