// Cấu trúc if
let age=16;
if(age>=18){
    console.log("Bạn đủ tuổi");
}else{
    console.log("Bạn chưa đủ tuổi");
}

// IF LỒNG
let score=7;
if(score>=9){
    console.log("Xuất sắc");
}else if(score>=7.5){
    console.log("Gioi");
}else if(score>=5){
    console.log("Trung bình");
}else{
    console.log("Yếu");
}